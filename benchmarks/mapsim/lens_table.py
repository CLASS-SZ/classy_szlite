"""CMB-lensing matched-filter noise σ_κ(θ500) for the stacked lensing observable.

    python benchmarks/mapsim/lens_table.py $MAPSIM_REF/so_lensing_noise

Our own filter, following Zubeldia & Challinor 2019 (arXiv:1904.07887, Eqs. 18-23),
the convention the paper (arXiv:2504.10230, Sec. II.1) points to:

* template: an NFW profile with c500 = 3, truncated in 3D at 5 R500, projected
  numerically, normalised to 1 at the scale radius (so the amplitude is κ(r_s));
* noise: the SO minimum-variance quadratic-estimator curve (column 7) of the
  so_noise_models v3.1.1 files with the tSZ deprojected (deproj1),
  reconstruction noise only;
* σ_κ² = [∫ ℓ dℓ τ(ℓ)² / (2π N(ℓ))]⁻¹ over the file's range, 2 ≤ ℓ ≤ 5000, flat
  sky, τ the Hankel transform of the template.

On the baseline curve (SENS1) this reproduces cosmocnc_jax's table
(``so_sim_lensing_mf_noise.npy``, 0.74'-5.87') to 0.35% in level and 0.3% in
shape, with no free factor. The paper's text cites the deproj0 file, but deproj0
gives a table 1/0.69 lower at the same shape: the table was made with the
tSZ-deprojected curve, the physically sensible choice for clusters, whose own
tSZ would bias a standard reconstruction. Goal depth uses the deproj1 SENS2 file.

Writes classy_szlite/sim/lens_tables.py (θ grid in arcmin, σ_κ for SO baseline
and goal), and prints the comparison with the reference table.
"""
from __future__ import annotations

import os
import sys

import numpy as np
from scipy.integrate import quad
from scipy.special import j0

C500, X_TRUNC = 3.0, 15.0                        # concentration; truncation radius / r_s (5 R500)
ARCMIN = np.pi / 180.0 / 60.0
LMIN, LMAX = 2.0, 5000.0
FILES = {"baseline": "lensing_v3_1_1_nlkk_v3_1_0_deproj1_SENS1_fsky0p4_qe_lT30-3000_lP30-5000.dat",
         "goal": "lensing_v3_1_1_nlkk_v3_1_0_deproj1_SENS2_fsky0p4_qe_lT30-3000_lP30-5000.dat"}
THETA = np.geomspace(0.1, 60.0, 81)              # θ500 grid [arcmin]


def sigma_projected(x):
    """Projected 3D-truncated NFW at R = x r_s, in units of ρ0 r_s."""
    if x >= X_TRUNC:
        return 0.0
    zmax = np.sqrt(X_TRUNC ** 2 - x * x)
    f = lambda z: 1.0 / (np.hypot(x, z) * (1.0 + np.hypot(x, z)) ** 2)
    return 2.0 * quad(f, 0.0, zmax, limit=400, points=[min(1.0, zmax)])[0]


XG = np.concatenate([np.geomspace(1e-5, 1.0, 500, endpoint=False), np.linspace(1.0, X_TRUNC, 700)])
SG = np.array([sigma_projected(x) for x in XG])
S_AT_RS = sigma_projected(1.0)                   # 0.66259 = 2(2-3R+R³)/(3(R²-1)^1.5), R = 15


def tau(ell, theta_s_rad):
    th = XG * theta_s_rad
    w = np.gradient(th)
    return 2.0 * np.pi * np.array([np.sum(SG / S_AT_RS * j0(l * th) * th * w) for l in ell])


def sigma_kappa(theta500_arcmin, ell, N):
    t = tau(ell, theta500_arcmin * ARCMIN / C500)
    return float((np.sum(ell * t * t / N) / (2.0 * np.pi)) ** -0.5)


def main():
    ref_dir = sys.argv[1]
    curves = {}
    for mode, fn in FILES.items():
        d = np.loadtxt(os.path.join(ref_dir, fn))
        sel = (d[:, 0] >= LMIN) & (d[:, 0] <= LMAX)
        curves[mode] = (d[sel, 0], d[sel, 7])
    raw = {m: np.array([sigma_kappa(t, *curves[m]) for t in THETA]) for m in FILES}

    ref = np.load(os.path.join(ref_dir, "so_sim_lensing_mf_noise.npy"))
    th_ref = ref[0] / ARCMIN
    ours = np.exp(np.interp(np.log(th_ref), np.log(THETA), np.log(raw["baseline"])))
    ratio = ref[1] / ours
    k = float(np.median(ratio))
    assert abs(k - 1.0) < 0.01, f"reference table / ours = {k:.4f}: the convention no longer matches"
    print(f"S(r_s)/(rho0 r_s) = {S_AT_RS:.5f}")
    print(f"reference table / ours (baseline), {th_ref.min():.2f}'-{th_ref.max():.2f}': median {k:.4f}, "
          f"shape within {np.max(np.abs(ratio / k - 1)):.4f}")
    print("goal / baseline sigma_kappa at 0.5', 1', 2', 5', 10':",
          np.round(np.interp(np.log([0.5, 1, 2, 5, 10]), np.log(THETA), raw["goal"] / raw["baseline"]), 4).tolist())

    out = os.path.join(os.path.dirname(__file__), "..", "..", "classy_szlite", "sim", "lens_tables.py")
    fmt = lambda a: "np.array([" + ", ".join(f"{v:.8g}" for v in a) + "])"
    with open(out, "w") as fh:
        fh.write('"""CMB-lensing matched-filter noise σ_κ(θ500) for SO baseline and goal.\n\n'
                 "Generated by benchmarks/mapsim/lens_table.py (do not edit): our truncated-NFW\n"
                 "filter (c500 = 3, 5 R500, amplitude κ at the scale radius) on the SO v3.1.1\n"
                 "minimum-variance lensing noise curves with the tSZ deprojected, 2 ≤ ℓ ≤ 5000.\n"
                 f"cosmocnc_jax's baseline table / ours = {k:.4f}, shape within\n"
                 f"{np.max(np.abs(ratio / k - 1)):.4f} over 0.74'-5.87' (no free factor applied).\n"
                 '"""\nimport numpy as np\n\n'
                 f"THETA500_ARCMIN = {fmt(THETA)}\n"
                 f"SIGMA_KAPPA = {{\n    \"baseline\": {fmt(raw['baseline'])},\n"
                 f"    \"goal\": {fmt(raw['goal'])},\n}}\n")
    print("wrote", os.path.normpath(out))


if __name__ == "__main__":
    main()
